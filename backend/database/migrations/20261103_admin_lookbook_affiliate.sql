-- Add the Lookbook moderation and affiliate withdrawal schema used by the Admin portal.
-- Apply once after schema_mysql.sql.
USE QuanLyCuaHangVai;
SET NAMES utf8mb4;

ALTER TABLE NHAN_VIEN
    ADD COLUMN SDT VARCHAR(15) NULL,
    ADD COLUMN SoTaiKhoan VARCHAR(50) NULL,
    ADD COLUMN NganHang VARCHAR(100) NULL,
    ADD COLUMN TenTiemMay VARCHAR(150) NULL,
    ADD COLUMN CapBac VARCHAR(50) NULL,
    ADD COLUMN AffiliateCode VARCHAR(50) NULL;

ALTER TABLE BIEN_THE_SP
    ADD COLUMN MaVaiCode VARCHAR(50) NULL,
    ADD COLUMN HinhAnh VARCHAR(500) NULL;

ALTER TABLE BANG_GIA
    ADD COLUMN TyLeHoaHong DECIMAL(5,2) NOT NULL DEFAULT 0;

ALTER TABLE VI_HOA_HONG
    ADD COLUMN TongTichLuy DECIMAL(18,2) NOT NULL DEFAULT 0;

ALTER TABLE LOOKBOOK
    ADD COLUMN DanhMuc VARCHAR(100) DEFAULT 'Đầm & Váy',
    ADD COLUMN MaBienThe INT NULL,
    ADD COLUMN DinhLuongVai VARCHAR(50) NULL,
    ADD COLUMN MoTa TEXT NULL,
    ADD COLUMN TrangThaiDuyet VARCHAR(30) NOT NULL DEFAULT 'Chờ duyệt',
    ADD COLUMN NgayDang DATETIME DEFAULT CURRENT_TIMESTAMP,
    ADD CONSTRAINT FK_LOOKBOOK_BIENTHE FOREIGN KEY (MaBienThe) REFERENCES BIEN_THE_SP(MaBienThe) ON DELETE SET NULL;

CREATE TABLE YEU_CAU_RUT_TIEN (
    MaYeuCau INT AUTO_INCREMENT PRIMARY KEY,
    MaNV INT NOT NULL,
    SoTien DECIMAL(18,2) NOT NULL,
    HinhThuc VARCHAR(50) NOT NULL,
    ThongTinNhan VARCHAR(255) NULL,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Chờ duyệt',
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_RUTTIEN_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE LICH_SU_HOA_HONG (
    MaLS INT AUTO_INCREMENT PRIMARY KEY,
    MaNV INT NOT NULL,
    MaDonHangCode VARCHAR(50) NULL,
    LoaiGiaoDich VARCHAR(150) NOT NULL,
    SoTien DECIMAL(18,2) NOT NULL,
    TrangThai VARCHAR(30) NOT NULL DEFAULT 'Thành công',
    NgayTao DATETIME DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_LSHH_NV FOREIGN KEY (MaNV) REFERENCES NHAN_VIEN(MaNV)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;